declare(strict_types=1);

namespace GaletteObjectsLend\IO;

use Galette\IO\Pdf;
use Galette\Core\Db;
use Galette\Core\Preferences;
use GaletteObjectsLend\LendPreferences;
use GaletteObjectsLend\Entity\LendObject;
use GaletteObjectsLend\Repository\Rents;

/**
 * Object card PDF
 *
 * @author Johan Cwiklinski <johan@x-tnd.be>
 */
class PdfObject extends Pdf
{
    /** @var array<string> Tags kept in HTML values */
    private const array HTML_TAGS = [
        'a', 'b', 'blockquote', 'br', 'em', 'h1', 'h2', 'h3', 'h4', 'h5', 'h6', 'i',
        'li', 'ol', 'p', 's', 'span', 'strong', 'sub', 'sup', 'u', 'ul'
    ];

    /**
     * Main constructor
     *
     * @param Db              $zdb    Database instance
     * @param Preferences     $prefs  Preferences instance
     * @param LendPreferences $lprefs Plugin Preferences instance
     */
    public function __construct(private readonly Db $zdb, Preferences $prefs, private readonly LendPreferences $lprefs)
    {
        parent::__construct($prefs);
        // Disable Auto Page breaks
        $this->SetAutoPageBreak(auto: false, margin: $this->footer_height + 10);
        //TRANS: this is a filename
        $this->filename = _T('object_card', 'objectslend') . '.pdf';
    }

    /**
     * Initialize PDF
     */
    public function init(): void
    {
        // Set document information
        $this->SetTitle(_T('Object card', 'objectslend'));
        $this->SetSubject(_T('Generated by Galette'));
        $this->SetKeywords(_T('Labels', 'objectslend'));

        $this->setMargins(10, 10);

        // Show full page
        $this->SetDisplayMode('fullpage');

        //enable pagination
        $this->showPagination();

        parent::init();
    }

    /**
     * Draw listed object cards
     *
     * @param LendObject[] $objects Object list
     */
    public function drawCards(array $objects): void
    {
        $first = true;
        foreach ($objects as $object) {
            if (!$first) {
                $this->AddPage();
            }
            $first = false;
            $this->drawCard($object);
        }
    }

    /**
     * Draw object card
     *
     * @param LendObject $object Object
     */
    public function drawCard(LendObject $object): void
    {
        $this->SetFont(Pdf::FONT, 'B');
        $wpic = 0;
        $hpic = 0;
        $pic = $object->getPicture();
        if ($pic->hasPicture()) {
            // Set picture size to max width 30 mm or max height 30 mm
            $tw = $pic->getOptimalThumbWidth($this->lprefs);
            $th = $pic->getOptimalThumbHeight($this->lprefs);
            $ratio = $tw / $th;
            if ($ratio < 1) {
                if ($tw > 16) {
                    $hpic = 30;
                } else {
                    $hpic = $th;
                }
                $wpic = (int)round($hpic * $ratio);
            } else {
                if ($tw > 16) {
                    $wpic = 30;
                } else {
                    $wpic = $tw;
                }
                $hpic = (int)round($wpic / $ratio);
            }

            $this->Image(file: $pic->getThumb($this->lprefs), x: 10, y: 10, w: $wpic, h: $hpic);
        }

        $this->addCell(_T("Name", "objectslend"), $object->getName(), $wpic);
        if ($this->lprefs->isEnabled(LendPreferences::VIEW_DESCRIPTION)) {
            $this->addHtmlCell(_T("Description", "objectslend"), $object->getDescriptionHtml(), $wpic);
        }
        if ($this->lprefs->isEnabled(LendPreferences::VIEW_CATEGORY)) {
            $this->addCell(_T("Category", "objectslend"), $object->getCategoryName() ?? '', $wpic);
        }
        if ($this->lprefs->isEnabled(LendPreferences::VIEW_SERIAL)) {
            $this->addCell(_T("Serial number", "objectslend"), $object->getSerialNumber(), $wpic);
        }
        if ($this->lprefs->isEnabled(LendPreferences::VIEW_PRICE)) {
            $this->addCell(_T("Price", "objectslend"), number_format(
                num: $object->getPrice(),
                decimals: 2,
                decimal_separator: ',',
                thousands_separator: ' '
            ), $wpic);
        }
        if ($this->lprefs->isEnabled(LendPreferences::VIEW_LEND_PRICE)) {
            $this->addCell(
                _T("Borrow price", "objectslend"),
                number_format(
                    num: $object->getRentPrice(),
                    decimals: 2,
                    decimal_separator: ',',
                    thousands_separator: ' '
                ) . ' €'
                    . ($object->isPricePerDay() ? ' ' . _T("(per day)", "objectslend") : ''),
                $wpic
            );
        }
        if ($this->lprefs->isEnabled(LendPreferences::VIEW_DIMENSION)) {
            $this->addCell(_T("Dimensions", "objectslend"), $object->getDimension() . ' ' . _T('Cm', 'objectslend'), $wpic);
        }
        if ($this->lprefs->isEnabled(LendPreferences::VIEW_WEIGHT)) {
            $this->addCell(_T("Weight", "objectslend"), number_format(
                num: $object->getWeight(),
                decimals: 3,
                decimal_separator: ',',
                thousands_separator: ' '
            ) . ' ' . _T('Kg', 'objectslend'), $wpic);
        }
        $this->addCell(_T("Active", "objectslend"), $object->isObjectActive() ? 'X' : '', $wpic);
        $this->addCell(_T("Location", "objectslend"), $object->getStatusText(), $wpic);
        $this->addCell(_T("Since", "objectslend"), $object->getDateBegin(), $wpic);
        $this->addCell(_T("Member", "objectslend"), $object->getMemberName(), $wpic);
        if ($this->lprefs->isEnabled(LendPreferences::VIEW_DATE_FORECAST)) {
            $this->addCell(_T("Return", "objectslend"), $object->getDateForecast(), $wpic);
        }

        if ($this->GetY() < $hpic) {
            $this->SetY($hpic);
        }
        $this->Ln();

        $rents = (new Rents($this->zdb))->getForObject((int)$object->getId());

        $col_begin = 33;
        $col_end = 33;
        $col_status = 30;
        $col_stock = 25;
        $col_adh = 30;
        $col_comments = 40;

        $this->SetFont(Pdf::FONT, 'B', 10);
        $this->Cell(
            w: 0,
            h: 0,
            txt: _T("History of object loans", "objectslend"),
            border: 0,
            ln: 1,
            align: 'C'
        );
        $this->Ln();
        $this->Cell(
            w: $col_begin,
            h: 0,
            txt: $this->stretchHead(_T("Begin", "objectslend"), $col_begin),
            border: 'B'
        );
        $this->Cell(
            w: $col_end,
            h: 0,
            txt: $this->stretchHead(_T("End", "objectslend"), $col_end),
            border: 'B'
        );
        $this->Cell(
            w: $col_status,
            h: 0,
            txt: $this->stretchHead(_T("Status", "objectslend"), $col_status),
            border: 'B'
        );
        $this->Cell(
            w: $col_stock,
            h: 0,
            txt: $this->stretchHead(_T("In stock", "objectslend"), $col_stock),
            border: 'B'
        );
        $this->Cell(
            w: $col_adh,
            h: 0,
            txt: $this->stretchHead(_T("Member", "objectslend"), $col_adh),
            border: 'B'
        );
        $this->Cell(
            w: $col_comments,
            h: 0,
            txt: $this->stretchHead(_T("Comments", "objectslend"), $col_comments),
            border: 'B'
        );
        $this->Ln();
        $this->SetFont(Pdf::FONT, '', 9);

        foreach ($rents as $rt) {
            $this->Cell(w: $col_begin, h: 0, txt: $this->cut($rt->getDateBegin(), $col_begin), border: 'B');
            $this->Cell(w: $col_end, h: 0, txt: $this->cut($rt->getDateEnd(), $col_end), border: 'B');
            $this->Cell(w: $col_status, h: 0, txt: $this->cut($rt->getStatusText(), $col_status), border: 'B');
            $this->Cell(w: $col_stock, h: 0, txt: $rt->isInStock() ? '    X' : '', border: 'B');
            $this->Cell(w: $col_adh, h: 0, txt: $this->cut($rt->getMemberName(), $col_adh), border: 'B');
            $this->Cell(w: $col_comments, h: 0, txt: $this->cut($rt->getComments(), $col_comments), border: 'B');
            $this->Ln();
        }
    }


    /**
     * Add a line in the array
     *
     * @param string $title Line title
     * @param string $value Line value
     * @param int    $width Cell width
     */
    private function addCell(string $title, string $value, int $width): void
    {
        if ($width > 0) {
            $this->Cell($width, 0, '');
        }
        $this->SetFont(Pdf::FONT, 'B', 9);
        $padding = 50;
        $this->Cell($padding, 0, $this->cut($title, $padding));

        $this->SetFont(Pdf::FONT, '', 9);
        $wrapped = explode("\n", wordwrap($value, 150 - $padding - $width, "\n"));
        $i = 0;
        foreach ($wrapped as $w) {
            if ($i++ > 0) {
                $this->Cell($width + $padding, 0, '');
            }
            $this->MultiCell(w: 0, h: 0, txt: $w, border: 0, align: 'L');
        }
    }

    /**
     * Add a cell whose value is sanitized HTML
     *
     * Only text formatting is kept: TCPDF would load an image source from the
     * server, be it an internal URL or a local file.
     *
     * @param string $title Cell title
     * @param string $html  Cell value
     * @param int    $width Picture width
     */
    private function addHtmlCell(string $title, string $html, int $width): void
    {
        $html = strip_tags($html, self::HTML_TAGS);

        if ($width > 0) {
            $this->Cell($width, 0, '');
        }
        $this->SetFont(Pdf::FONT, 'B', 9);
        $padding = 50;
        $this->Cell($padding, 0, $this->cut($title, $padding));

        $this->SetFont(Pdf::FONT, '', 9);
        $this->MultiCell(
            w: 0,
            h: 0,
            txt: $html,
            border: 0,
            align: 'L',
            fill: false,
            ln: 1,
            x: null,
            y: null,
            reseth: true,
            stretch: 0,
            ishtml: true
        );
    }
}
