declare(strict_types=1);

namespace GaletteObjectsLend\IO;

use Galette\Core\Db;
use Galette\IO\Pdf;
use Galette\Util\Html;
use Galette\Core\Preferences;
use Galette\Core\Login;
use GaletteObjectsLend\Entity\LendObject;
use GaletteObjectsLend\Entity\LendCategory;
use GaletteObjectsLend\LendPreferences;

/**
 * Object labels PDF
 *
 * @author Johan Cwiklinski <johan@x-tnd.be>
 */
class PdfObjects extends Pdf
{
    public const int LIST_FONT = self::FONT_SIZE - 2;

    /**
     * Main constructor, set creator and author
     *
     * @param Db              $zdb        Database instance
     * @param Preferences     $prefs      Preferences
     * @param LendPreferences $lendsprefs Plugin preferences
     * @param Login           $login      Login instance
     */
    public function __construct(
        private readonly Db $zdb,
        Preferences $prefs,
        private readonly LendPreferences $lendsprefs,
        private readonly Login $login,
    ) {
        parent::__construct($prefs);
        // Enable Auto Page breaks
        $this->SetAutoPageBreak(auto: true, margin: $this->footer_height + 10);

        //TRANS: this is a filename
        $this->filename = _T('objects_cards', 'objectslend') . '.pdf';
    }

    /**
     * Initialize PDF
     */
    public function init(): void
    {
        // Set document information
        $this->SetTitle(_T("Objects list", "objectslend"));
        $this->SetSubject(_T("Generated by Galette"));
        $this->SetKeywords(_T("Objects list", "objectslend"));

        $this->setPageOrientation('L');
        $this->setHeaderMargin(10);

        //enable pagination
        $this->showPagination();

        parent::init();
    }

    /**
     * Page header
     *
     * @phpcs:disable
     */
    public function Header(): void
    {
        // @phpcs:enable
        $this->SetFont(Pdf::FONT, 'B');
        $x = $this->getX();
        $this->Cell(
            w: 0,
            h: 10,
            txt: _T("Objects list", "objectslend"),
            border: 0,
            ln: 0,
            align: 'C',
            fill: false,
            link: '',
            stretch: 0,
            ignore_min_height: false,
            calign: 'M',
            valign: 'M'
        );
        $this->SetFont(Pdf::FONT, '', self::LIST_FONT);
        $this->setX($x);
        $this->Cell(
            w: 0,
            h: 10,
            txt: str_replace(
                '%date',
                date(_T("Y-m-d")),
                _T("Printed on %date", "objectslend")
            ),
            border: 0,
            ln: 0,
            align: 'R',
            fill: false,
            link: '',
            stretch: 0,
            ignore_min_height: false,
            calign: 'M',
            valign: 'M'
        );
    }

    /**
     * Draw objects list
     *
     * @param LendObject[] $objects List of objects
     */
    public function drawList(array $objects): void
    {
        $this->Ln(10); //for Header

        // Header
        $this->SetFillColor(255, 255, 255);

        $w_checkbox = 5;
        $w_name = 33;
        $w_description = 45;
        $w_serial = 21;
        $w_price = 17;
        $w_dimension = 28;
        $w_weight = 16;
        $w_status = 26;
        $w_date = 22;
        $w_adherent = 26;

        $this->Cell(
            w: $w_checkbox,
            h: 0,
            txt: $this->stretchHead('', $w_checkbox),
            border: 1,
            ln: 0,
            align: 'C',
            fill: true
        );
        $this->Cell(
            w: $w_name,
            h: 0,
            txt: $this->stretchHead(_T("Name", "objectslend"), $w_name),
            border: 1,
            ln: 0,
            align: 'C',
            fill: true
        );
        $this->Cell(
            w: $w_description,
            h: 0,
            txt: $this->stretchHead(_T("Description", "objectslend"), $w_description),
            border: 1,
            ln: 0,
            align: 'C',
            fill: true
        );
        $this->Cell(
            w: $w_serial,
            h: 0,
            txt: $this->stretchHead(_T("Serial", "objectslend"), $w_serial),
            border: 1,
            ln: 0,
            align: 'C',
            fill: true
        );
        $this->Cell(
            w: $w_price,
            h: 0,
            txt: $this->stretchHead(_T("Price", "objectslend"), $w_price),
            border: 1,
            ln: 0,
            align: 'C',
            fill: true
        );
        $this->Cell(
            w: $w_price,
            h: 0,
            txt: $this->stretchHead(_T("Borrow price", "objectslend"), $w_price),
            border: 1,
            ln: 0,
            align: 'C',
            fill: true
        );
        $this->Cell(
            w: $w_dimension,
            h: 0,
            txt: $this->stretchHead(_T("Dimensions", "objectslend"), $w_dimension),
            border: 1,
            ln: 0,
            align: 'C',
            fill: true
        );
        $this->Cell(
            w: $w_weight,
            h: 0,
            txt: $this->stretchHead(_T("Weight", "objectslend"), $w_weight),
            border: 1,
            ln: 0,
            align: 'C',
            fill: true
        );
        $this->Cell(
            w: $w_status,
            h: 0,
            txt: $this->stretchHead(_T("Status", "objectslend"), $w_status),
            border: 1,
            ln: 0,
            align: 'C',
            fill: true
        );
        $this->Cell(
            w: $w_date,
            h: 0,
            txt: $this->stretchHead(_T("Since", "objectslend"), $w_date),
            border: 1,
            ln: 0,
            align: 'C',
            fill: true
        );
        $this->Cell(
            w: $w_adherent,
            h: 0,
            txt: $this->stretchHead(_T("Member", "objectslend"), $w_adherent),
            border: 1,
            ln: 0,
            align: 'C',
            fill: true
        );
        $this->Cell(
            w: $w_date,
            h: 0,
            txt: $this->stretchHead(_T("Return", "objectslend"), $w_date),
            border: 1,
            ln: 1,
            align: 'C',
            fill: true
        );

        $this->SetFont('');

        //objects come ordered by category: a heading, and the previous
        //category subtotal, each time it changes
        $current_category = null;
        $sum_price = 0;
        $grant_total = 0;
        $row = 0;

        foreach ($objects as $object) {
            $category_id = (int)$object->getCategoryId();
            if (
                $this->lendsprefs->isEnabled(LendPreferences::VIEW_CATEGORY)
                && $current_category !== $category_id
            ) {
                $this->SetFont('', 'B');

                if (($this->login->isAdmin() || $this->login->isStaff()) && $sum_price > 0) {
                    $width = $w_checkbox + $w_name + $w_description + $w_serial + $w_price;
                    $this->Cell(
                        w: $width,
                        h: 0,
                        txt: number_format(num: $sum_price, decimals: 2, decimal_separator: ',', thousands_separator: ''),
                        border: '',
                        ln: 0,
                        align: 'R'
                    );
                    $sum_price = 0;
                    $this->Ln();
                }

                if ($category_id > 0) {
                    $category = new LendCategory($this->zdb, $category_id);
                    $text = str_replace(
                        '%category',
                        $category->getName(count: false),
                        _T("Category: %category", "objectslend")
                    );
                } else {
                    $text = _T("No category", "objectslend");
                }
                $this->Cell(w: 0, h: 0, txt: $text, border: 0, ln: 1, align: 'C');
                $current_category = $category_id;

                $this->SetFont('');
            }

            if ($row++ % 2 == 0) {
                $this->SetFillColor(255, 189, 64);
            } else {
                $this->SetFillColor(255, 214, 135);
            }

            $fill = !$object->inStock();
            $this->Cell(w: $w_checkbox, h: 0, txt: '□', border: 'B', ln: 0, align: 'L', fill: $fill);
            $this->Cell(
                w: $w_name,
                h: 0,
                txt: $this->cut($object->getName(), $w_name),
                border: 'B',
                ln: 0,
                align: 'L',
                fill: $fill
            );
            $this->Cell(
                w: $w_description,
                h: 0,
                txt: $this->cut($this->oneLine($object->getDescriptionHtml()), $w_description),
                border: 'B',
                ln: 0,
                align: 'L',
                fill: $fill
            );
            $this->Cell(
                w: $w_serial,
                h: 0,
                txt: $this->cut($object->getSerialNumber(), $w_serial),
                border: 'B',
                ln: 0,
                align: 'L',
                fill: $fill
            );
            $this->Cell(
                w: $w_price,
                h: 0,
                txt: $this->cut(number_format(
                    num: $object->getPrice(),
                    decimals: 2,
                    decimal_separator: ',',
                    thousands_separator: ' '
                ), $w_price),
                border: 'B',
                ln: 0,
                align: 'R',
                fill: $fill
            );
            $this->Cell(
                w: $w_price,
                h: 0,
                txt: $this->cut(number_format(
                    num: $object->getRentPrice(),
                    decimals: 2,
                    decimal_separator: ',',
                    thousands_separator: ' '
                ), $w_price) . '€',
                border: 'B',
                ln: 0,
                align: 'R',
                fill: $fill
            );
            $this->Cell(
                w: $w_dimension,
                h: 0,
                txt: $this->cut($object->getDimension(), $w_dimension),
                border: 'B',
                ln: 0,
                align: 'L',
                fill: $fill
            );
            $this->Cell(
                w: $w_weight,
                h: 0,
                txt: $this->cut(number_format(
                    num: $object->getWeight(),
                    decimals: 3,
                    decimal_separator: ',',
                    thousands_separator: ' '
                ), $w_weight),
                border: 'B',
                ln: 0,
                align: 'R',
                fill: $fill
            );
            $this->Cell(
                w: $w_status,
                h: 0,
                txt: $this->cut($object->getStatusText(), $w_status),
                border: 'B',
                ln: 0,
                align: 'L',
                fill: $fill
            );
            $this->Cell(
                w: $w_date,
                h: 0,
                txt: $this->cut($object->getDateBegin(), $w_date),
                border: 'B',
                ln: 0,
                align: 'L',
                fill: $fill
            );
            $this->Cell(
                w: $w_adherent,
                h: 0,
                txt: $this->cut($object->getMemberName(), $w_adherent),
                border: 'B',
                ln: 0,
                align: 'L',
                fill: $fill
            );
            $this->Cell(
                w: $w_date,
                h: 0,
                txt: $this->cut($object->getDateForecast(), $w_date),
                border: 'B',
                ln: 1,
                align: 'L',
                fill: $fill
            );

            if ($this->login->isAdmin() || $this->login->isStaff()) {
                $sum_price += $object->getPrice();
                $grant_total += $object->getPrice();
            }
        }

        if (($this->login->isAdmin() || $this->login->isStaff())) {
            $width = $w_checkbox + $w_name + $w_description + $w_serial + $w_price;
            $this->Cell(
                w: $width,
                h: 0,
                txt: number_format(num: $sum_price, decimals: 2, decimal_separator: ',', thousands_separator: ''),
                border: '',
                ln: 0,
                align: 'R'
            );
            $this->Ln();
            $this->Ln();

            $this->Cell(
                w: $width,
                h: 0,
                txt: _T("Total:", "objectslend") . ' ' . number_format(num: $grant_total, decimals: 2, decimal_separator: ',', thousands_separator: ''),
                border: '',
                ln: 0,
                align: 'R'
            );
            $this->Ln();
        }

        $this->Ln();

        $this->Cell(w: $w_price, h: 0, txt: '', border: true, ln: 0, align: '', fill: true);
        $this->Cell(w: 0, h: 0, txt: _T("Borrowed", "objectslend"), border: 0, ln: 1);
        $this->Cell(w: $w_price, h: 0, txt: '', border: true);
        $this->Cell(w: 0, h: 0, txt: _T("Available", "objectslend"), border: 0, ln: 1);
    }

    /**
     * HTML description as a single line of text
     *
     * @param string $html Description
     */
    private function oneLine(string $html): string
    {
        //blocks are only separated by their tags, which are about to go
        $html = (string)preg_replace('#<(/?(?:p|br|li|ul|ol|div|h[1-6]|tr|td)\b)#i', ' <$1', $html);
        return trim((string)preg_replace('/\s+/u', ' ', Html::strip($html)));
    }
}
